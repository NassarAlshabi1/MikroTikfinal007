// ============================================================
//  مقارنة: قبل vs بعد تطبيق select()
// ============================================================
//
//  ┌──────────────────────────────────────────────────────────┐
//  │ قبل: ref.watch(provider) — كل شيء يُعاد بناؤه           │
//  └──────────────────────────────────────────────────────────┘
//
//   state change: { loading: true → false }
//                    ↓
//   ┌───────────────────────────────────────────────────────┐
//   │ Scaffold (rebuild)                                    │
//   │   ├── AppBar (rebuild)         ← loading تأثّر        │
//   │   ├── ListView (rebuild)       ← loading لم يتأثر!!  │
//   │   │     ├── ListTile[0] (rebuild)                    │
//   │   │     ├── ListTile[1] (rebuild)                    │
//   │   │     └── ... 100 عنصر (rebuild)                   │
//   │   └── PaginationBar (rebuild)  ← loading تأثّر        │
//   └───────────────────────────────────────────────────────┘
//   النتيجة: إعادة بناء 100+ widget عند كل تغيير في loading
//
//  ┌──────────────────────────────────────────────────────────┐
//  │ بعد: ref.watch(provider.select(...)) — عزل دقيق        │
//  └──────────────────────────────────────────────────────────┘
//
//   state change: { loading: true → false }
//                    ↓
//   ┌───────────────────────────────────────────────────────┐
//   │ Scaffold (no rebuild — لا watch مباشر)                │
//   │   ├── AppBar (rebuild)         ← loading تأثّر        │
//   │   │     └── IconButton (rebuild)                     │
//   │   ├── ListView (NO rebuild)    ← select(items) لم يتغير│
//   │   │     └── ListTile[*] (NO rebuild)                  │
//   │   └── PaginationBar (rebuild)  ← loading تأثّر        │
//   └───────────────────────────────────────────────────────┘
//   النتيجة: إعادة بناء ~3 widgets فقط بدل 100+
//
//  على جهاز ضعيف (CPU 1.4 GHz, 1GB RAM):
//   - قبل: كل refresh ⇒ 200ms+ تجمد (jank)
//   - بعد: كل refresh ⇒ <16ms (60fps سلس)
